using DynamicQueryBuilder.Models.Enums.Helpers.Databases;

namespace DynamicQueryBuilder.Models.Helpers;

/// <summary>
///     Configuration Object to initialize the library.
/// </summary>
/// <remarks>
///     Known issue: this is a positional record, so its compiler-generated <c>ToString()</c> includes the
///     connection string, password included. Do not log instances of this type.
/// </remarks>
/// <param name="ConnectionString">
///     Database connection string, in the format of the driver selected by <paramref name="DatabaseDriver"/>
///     (Npgsql for PostgreSQL, MySql.Data for MySQL).
/// </param>
/// <param name="DatabaseDriver">
///     Database driver used to open the connection and to choose the catalog query that reads the metadata.
///     It does not change the SQL generated by the query builder.
/// </param>
public record DynamicQueryBuilderSettings(string ConnectionString, DatabaseDriver DatabaseDriver);
